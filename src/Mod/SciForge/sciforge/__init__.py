"""SciForge: the Fusion-style interface layer of the SciForge fork of FreeCAD.

This package must stay importable outside FreeCAD (the *_core modules are
pure Python and are unit tested), so nothing here imports FreeCAD or Qt at
module level except inside the logging helpers.
"""

import os

ROOT = os.path.dirname(os.path.abspath(__file__))

# SciForge's version lives in one file, VERSION next to this package (the C++ build, the
# installer and the release scripts read the same file). The literal is the fallback if the
# file is missing; SciForgeTests/unit/test_version_core.py checks both say the same.
_FALLBACK_VERSION = "0.1.0-beta.3.1.2"


def _read_version():
    try:
        with open(os.path.join(os.path.dirname(ROOT), "VERSION"), "r", encoding="utf-8") as handle:
            text = handle.readline().strip()
        return text or _FALLBACK_VERSION
    except Exception:
        return _FALLBACK_VERSION


__version__ = _read_version()


def icon_path(name):
    return os.path.join(ROOT, "icons", name)


# The icons' light strokes and white marks (made for the dark ribbon) and the dark grey they
# take in the light look (theme.py)
_LIGHT_INK = {
    "#dfe3e8": "#3b4453",  # strokes
    "#f5f5f5": "#3b4453",  # white marks
    "#ececec": "#c9ced6",  # the neutral solids' faces, a step darker on a white ribbon
    "#d2d4d7": "#aab1bb",
    "#aeb2b8": "#8a929d",
    "#e3e8ee": "#b9c2ce",  # the folder
    "#c9d1dc": "#97a3b3",
}
_KEEP_WHITE = {"palette_check"}  # (drawn on the blue of a ticked box)


def ui_icon_path(name):
    """Path of a ribbon/menu icon generated by tools/sciforge/make_icons.py; in the light
    look, a copy with dark strokes (made once in SciForge's user folder)."""
    path = os.path.join(ROOT, "icons", "ui", name + ".svg")
    try:
        from . import theme

        if theme.is_light() and name not in _KEEP_WHITE and os.path.isfile(path):
            return _light_copy(name, path)
    except Exception:
        pass
    return path


def _light_copy(name, path):
    import FreeCAD

    folder = os.path.join(FreeCAD.getUserAppDataDir(), "SciForge", "icons-light")
    target = os.path.join(folder, name + ".svg")
    if not os.path.isfile(target) or os.path.getmtime(target) < os.path.getmtime(path):
        with open(path, "r", encoding="utf-8") as handle:
            text = handle.read()
        for dark, ink in _LIGHT_INK.items():
            text = text.replace(dark, ink).replace(dark.upper(), ink)
        os.makedirs(folder, exist_ok=True)
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(text)
    return target


_ICON_CACHE = {}


def ui_icon(name):
    """QIcon for a ribbon/menu icon (empty icon if name is None or missing)."""
    from .compat import QtGui

    if not name:
        return QtGui.QIcon()
    if name not in _ICON_CACHE:
        path = ui_icon_path(name)
        if not os.path.isfile(path):
            warn("missing icon %s" % name)
            path = ui_icon_path("not_available")
        _ICON_CACHE[name] = QtGui.QIcon(path)
    return _ICON_CACHE[name]


# The last SciForge messages, shown (copyable) in SciForge > Diagnostics: FreeCAD's
# own error pop-ups fade away before they can be copied.
RECENT = []
RECENT_MAX = 200


def _remember(kind, msg):
    import time

    RECENT.append("%s %s %s" % (time.strftime("%H:%M:%S"), kind, msg))
    del RECENT[:-RECENT_MAX]


def _console():
    try:
        import FreeCAD

        return FreeCAD.Console
    except ImportError:
        return None


def log(msg):
    _remember("info", msg)
    console = _console()
    if console:
        console.PrintMessage("[SciForge] %s\n" % msg)
    else:
        print("[SciForge] %s" % msg)


def warn(msg):
    _remember("WARNING", msg)
    console = _console()
    if console:
        console.PrintWarning("[SciForge] %s\n" % msg)
    else:
        print("[SciForge] WARNING: %s" % msg)
